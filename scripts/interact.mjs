// Recorre las interacciones: abrir ventana con clic (a mitad y al final), cambiar de proyecto con →, Esc, idioma EN.
import { chromium } from 'playwright';
const url = process.argv[2] ?? 'http://127.0.0.1:5181/';
const out = process.argv[3] ?? '.impeccable/review/shots';
const b = await chromium.launch({ args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await p.goto(url, { waitUntil: 'networkidle' });
await p.waitForTimeout(2500);
await p.evaluate(() => { const el = document.querySelector('.case--lanzamet'); scrollTo(0, el.getBoundingClientRect().top + scrollY); });
await p.waitForTimeout(4000);
await p.click('.case--lanzamet [data-open]');
await p.waitForTimeout(380);
await p.screenshot({ path: `${out}/i-open-mid.png` });
await p.waitForTimeout(1500);
console.log('url tras abrir', p.url(), await p.title());
await p.keyboard.press('ArrowRight');
await p.waitForTimeout(1200);
console.log('url tras →', p.url());
await p.screenshot({ path: `${out}/i-aceslan.png` });
await p.keyboard.press('Escape');
await p.waitForTimeout(1300);
console.log('url tras Esc', p.url(), 'ventana oculta', await p.evaluate(() => document.getElementById('win').hidden));
await p.evaluate(() => scrollTo(0, 0));
await p.waitForTimeout(1500);
await p.click('[data-lang="en"]');
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/i-en-hero.png` });
await p.goBack();
await p.waitForTimeout(800);
console.log('errores', errors);
await b.close();
